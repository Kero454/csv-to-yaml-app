    print(f"  Descriptor:     {desc_path}")
    print(f"  Helm chart:     {chart_dir}")
    print(f"  Build dir:      {build_dir}")
    print()
    print("  xApp Descriptor (config-file.json):")
    print(json.dumps(descriptor, indent=4))
    print()
    print("  Next steps:")
    print(f"    1. Register in catalog:  curl -X POST http://localhost:8080/models \\")
    print(f"         -H 'Content-Type: application/json' -d @{desc_path}")
    print(f"    2. Deploy via Helm:      helm install {args.name} {chart_dir} --namespace ricxapp")
    print("=" * 60)

    return build_dir, image_tag, descriptor


