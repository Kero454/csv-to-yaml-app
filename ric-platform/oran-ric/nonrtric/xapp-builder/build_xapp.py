# Health Check HTTP Server
# ============================================================
class HealthHandler(BaseHTTPRequestHandler):
    """HTTP handler for Kubernetes liveness/readiness probes."""
    xapp_ref = None

    def do_GET(self):
        if self.path == "/health" or self.path == "/ready":
            status = self.server.xapp_ref.get_health_status() if self.server.xapp_ref else {{"status": "unknown"}}
            code = 200 if status.get("healthy") else 503
            self.send_response(code)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(json.dumps(status).encode())
        elif self.path == "/metrics":
            metrics = self.server.xapp_ref.get_metrics() if self.server.xapp_ref else {{}}
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(json.dumps(metrics).encode())
        else:
            self.send_response(404)
            self.end_headers()

    def log_message(self, format, *args):
        pass  # Suppress health check logs


