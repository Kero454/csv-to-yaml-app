class SharedDataLayer:
    """
    Shared Data Layer interface for xApp state persistence.
    Uses Redis/DBAAS in production, in-memory dict for standalone mode.
    """
    def __init__(self, namespace):
        self.namespace = namespace
        self._store = {{}}
        self._connected = False
        try:
            import redis
            self._redis = redis.Redis(
                host=os.environ.get("DBAAS_SERVICE_HOST", "localhost"),
                port=int(os.environ.get("DBAAS_SERVICE_PORT", "6379"))
            )
            self._redis.ping()
            self._connected = True
            logger.info("SDL connected to Redis/DBAAS")
        except Exception:
            logger.info("SDL using in-memory store (Redis not available)")
            self._redis = None

    def set(self, key, value):
        full_key = f"{{self.namespace}}:{{key}}"
        if self._connected:
            self._redis.set(full_key, json.dumps(value))
        else:
            self._store[full_key] = value

    def get(self, key):
        full_key = f"{{self.namespace}}:{{key}}"
        if self._connected:
            val = self._redis.get(full_key)
            return json.loads(val) if val else None
        return self._store.get(full_key)

    def delete(self, key):
        full_key = f"{{self.namespace}}:{{key}}"
        if self._connected:
            self._redis.delete(full_key)
        else:
            self._store.pop(full_key, None)


