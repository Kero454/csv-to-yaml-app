    parser.add_argument("--version", default="1.0.0", help="xApp version")
    parser.add_argument("--type", default="generic", help="Model type (lstm, autoformer, etc.)")
    parser.add_argument("--demo", action="store_true", help="Run with a sample .pkl")
    parser.add_argument("--no-build", action="store_true", help="Generate files only, don't build image")
    parser.add_argument("--output-dir", default=None, help="Output directory for build artifacts")
    args = parser.parse_args()

    print("=" * 60)
    print("  xApp Builder: .pkl -> Docker Image + Descriptor")
    print("=" * 60)
    print()

    # Set up build directory
    if args.output_dir:
        build_dir = args.output_dir
        os.makedirs(build_dir, exist_ok=True)
    else:
        build_dir = tempfile.mkdtemp(prefix="xapp-build-")

    # Handle .pkl file
    if args.demo:
        args.name = "traffic-prediction-lstm"
        args.type = "lstm"
        args.version = "1.0.0"
        pkl_path = os.path.join(build_dir, "model.pkl")
        create_sample_pkl(pkl_path)
    elif args.pkl:
        pkl_path = os.path.abspath(args.pkl)
        if not os.path.exists(pkl_path):
            print(f"  [FAIL] .pkl file not found: {pkl_path}")
            sys.exit(1)
        shutil.copy2(pkl_path, os.path.join(build_dir, "model.pkl"))
    else:
        print("  [FAIL] Provide --pkl <path> or --demo")
        sys.exit(1)

    image_tag = f"{REGISTRY}/xapps/{args.name}:{args.version}"

    print(f"  [INPUT]")
    print(f"    Model: {args.name} v{args.version}")
    print(f"    Type: {args.type}")
    print(f"    PKL: {pkl_path}")
    print()

    # Step 1: Generate xApp wrapper (ML Model Runner)
    print("  [1/5] Generating xApp ML Model Runner wrapper...")
    generate_xapp_wrapper(build_dir, args.name, args.type)

