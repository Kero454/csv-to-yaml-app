# RMR Interface (RIC Message Router)
# ============================================================
class RMRInterface:
    """
    RMR (RIC Message Router) interface for xApp communication.
    Handles message send/receive with the Near-RT RIC platform.
    Falls back to socket-based messaging if ricxappframe not available.
    """
    def __init__(self, port):
        self.port = port
        self.mrc = None  # RMR message router context
        self._ready = False
        self._init_rmr()

    def _init_rmr(self):
        try:
            import ricxappframe.rmr as rmr
            self.mrc = rmr.rmr_init(str(self.port).encode(), rmr.RMR_MAX_RCV_BYTES, 0x00)
            while rmr.rmr_ready(self.mrc) == 0:
                time.sleep(0.1)
            self._ready = True
            logger.info(f"RMR initialized on port {{self.port}}")
        except ImportError:
            logger.warning("ricxappframe not installed - using standalone RMR stub")
            self._ready = True  # Stub mode
        except Exception as e:
            logger.error(f"RMR init failed: {{e}}")

    @property
    def ready(self):
        return self._ready

    def receive(self, timeout_ms=500):
        """Receive a message from RMR. Returns (msg_type, payload) or None."""
        if self.mrc is None:
            return None
        try:
            import ricxappframe.rmr as rmr
            sbuf = rmr.rmr_alloc_msg(self.mrc, 4096)
            sbuf = rmr.rmr_torcv_msg(self.mrc, sbuf, timeout_ms)
            if sbuf.contents.state == 0:  # RMR_OK
                msg_type = sbuf.contents.mtype
                payload = rmr.rmr_get_src(sbuf).decode()
                return (msg_type, payload)
            rmr.rmr_free_msg(sbuf)
        except Exception:
            pass
        return None

    def send(self, msg_type, payload, meid=""):
        """Send a message via RMR."""
        if self.mrc is None:
            logger.debug(f"RMR stub: send type={{msg_type}} payload={{payload[:100]}}")
            return True
        try:
            import ricxappframe.rmr as rmr
            sbuf = rmr.rmr_alloc_msg(self.mrc, len(payload))
            sbuf.contents.mtype = msg_type
            sbuf.contents.payload = payload.encode()
            sbuf.contents.len = len(payload)
            sbuf = rmr.rmr_send_msg(self.mrc, sbuf)
            success = sbuf.contents.state == 0
            rmr.rmr_free_msg(sbuf)
            return success
        except Exception as e:
            logger.error(f"RMR send failed: {{e}}")
            return False


